/**
 * WBS: One task per CLI command.
 *
 * Reads docs/_cli-commands.json (produced by 02-source-scan), spawns a task
 * for each command. Each spawned task instantiates the cli-command template
 * with substitution vars: name, handlerFile, line.
 */

import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const TEMPLATE_ROOT =
  '.converge/playbooks/docs/tasks/08-reference/wbs/templates';

export async function run(ctx) {
  const cliPath = join(ctx.projectDir, 'docs/_cli-commands.json');
  if (!existsSync(cliPath)) {
    throw new Error(
      'Missing docs/_cli-commands.json. ' +
        'It should have been generated by 02-source-scan ' +
        '(node .converge/playbooks/docs/scripts/scan-cli-commands.mjs).',
    );
  }

  const commands = JSON.parse(readFileSync(cliPath, 'utf-8'));
  if (!Array.isArray(commands) || commands.length === 0) {
    throw new Error('docs/_cli-commands.json has no commands');
  }

  // Filter out aliases (commands without handlers — main.ts has fall-through cases)
  // Actually keep them — the agent can document aliases inline.
  // But sort: well-known top-level commands first, then alpha.
  const ORDER = ['init', 'run', 'verify', 'status', 'reset', 'inspect', 'show', 'plan'];
  const sorted = [...commands].sort((a, b) => {
    const ai = ORDER.indexOf(a.name);
    const bi = ORDER.indexOf(b.name);
    if (ai !== -1 && bi !== -1) return ai - bi;
    if (ai !== -1) return -1;
    if (bi !== -1) return 1;
    return a.name.localeCompare(b.name);
  });

  for (let idx = 0; idx < sorted.length; idx++) {
    const cmd = sorted[idx];
    const prefix = String(idx + 1).padStart(3, '0');
    const slug = cmd.name.replace(/[^a-z0-9-]/gi, '-').toLowerCase();
    const taskId = `${prefix}-${slug}`;

    const vars = {
      prefix,
      slug,
      name: cmd.name,
      handlerFile: cmd.handlerFile || '',
      handler: cmd.handler || '',
      line: String(cmd.line ?? ''),
      pagePath: `docs/reference/cli/${slug}.md`,
    };

    const templatePath = `${TEMPLATE_ROOT}/cli-command/tasks/{{slug}}/TASK.md`;
    await ctx.spawn(
      { _type: 'template-ref', path: templatePath, vars },
      { id: taskId },
    );
  }
}
