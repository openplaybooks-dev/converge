/**
 * Stub image generation backend — returns a 1x1 PNG placeholder.
 * Used for testing the workflow without API costs.
 *
 * The caller is responsible for writing image_bytes to disk. This stub does
 * NOT touch the filesystem — it just returns a valid PNG buffer.
 */

export async function generate({ prompt, references = [], aspect_ratio = "1:1", seed = "auto", quality = "final" }) {
  // 1x1 transparent PNG (smallest valid PNG)
  const placeholder = Buffer.from([
    0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,  // PNG signature
    0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52,  // IHDR chunk length
    0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,  // 1x1
    0x08, 0x06, 0x00, 0x00, 0x00, 0x1f, 0x15, 0xc4,  // 8-bit RGBA
    0x89, 0x00, 0x00, 0x00, 0x0a, 0x49, 0x44, 0x41,  // IDAT chunk
    0x54, 0x78, 0x9c, 0x63, 0x00, 0x01, 0x00, 0x00,  // compressed data
    0x05, 0x00, 0x01, 0x0d, 0x0a, 0x2d, 0xb4, 0x00,  //
    0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae,  // IEND chunk
    0x42, 0x60, 0x82,                                 // CRC
  ]);

  return {
    image_bytes: placeholder,
    seed: typeof seed === 'number' ? seed : 42,
    model: "stub",
  };
}
